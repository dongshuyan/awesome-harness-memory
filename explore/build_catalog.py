"""Derive the atlas resource catalog from the public Markdown pages (stdlib only)."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://github.com/dongshuyan/awesome-harness-memory/blob/master/"


def plain(text):
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    return re.sub(r"[*`]", "", text).strip()


def build():
    entries = {}
    comparison = (ROOT / "resources/benchmarks.md").read_text().split("## Reading a reported result\n", 1)[1].strip().split("\n\n")[0]
    for kind in ("systems", "papers", "benchmarks", "fiction"):
        source = f"resources/{kind}.md"
        sections = re.findall(r"^## ([^\n]+)\n(.*?)(?=^## |\Z)", (ROOT / source).read_text(), re.M | re.S)
        for title, body in sections:
            if title == "Reading a reported result":
                continue
            slug = re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")
            paragraphs = [p.strip() for p in body.split("\n\n") if p.strip()]
            description = next(p for p in paragraphs if not re.search(r"https?://", p))
            entry = entries.setdefault(slug, {"id": slug, "title": title, "types": [], "sources": [], "entries": [], "summaries": {}})
            entry["types"].append(kind)
            entry["entries"].append({"label": kind, "path": source, "anchor": slug, "url": BASE + source + "#" + slug})
            entry["summaries"][kind] = plain(description)
            # Evaluation entries describe the protocol more fully than the timeline.
            # Keep every source summary, and identify the one used for the preview.
            if "summary" not in entry or kind == "benchmarks":
                entry["summary"] = plain(description)
                entry["summaryKind"] = kind
            if kind == "benchmarks":
                entry["evaluationNote"] = plain(comparison)
            for label, url in re.findall(r"\[([^\]]+)\]\((https?://[^\s)]+)\)", body):
                if url not in [item["url"] for item in entry["sources"]]:
                    entry["sources"].append({"label": label, "url": url})
            if kind == "fiction":
                analogy = next(p for p in paragraphs if p.startswith("**Design analogy:**"))
                entry["analogy"] = plain(analogy).removeprefix("Design analogy:").strip()
    return list(entries.values())


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    records = build()
    content = "/* Generated by build_catalog.py from public resource pages. */\n"
    content += "(function (root) {\n  const resources = " + json.dumps(records, ensure_ascii=False, indent=2) + ";\n"
    content += "  if (typeof module !== 'undefined' && module.exports) module.exports = resources;\n  else root.AtlasResources = resources;\n})(globalThis);\n"
    destination = Path(__file__).with_name("catalog.js")
    if args.check:
        if not destination.exists() or destination.read_text() != content:
            raise SystemExit("Catalog differs from public pages; run python3 explore/build_catalog.py")
        print(f"Catalog matches public pages: {len(records)} distinct resources.")
    else:
        destination.write_text(content)
        print(f"Generated {len(records)} distinct resources.")
